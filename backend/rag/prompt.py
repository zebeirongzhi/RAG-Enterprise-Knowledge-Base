def build_prompt(context_chunks: list[dict], question: str) -> str:
    context_text = "\n\n---\n".join(
        f"[来源: {c['product_name']}/{c['model_name']}/{c['filename']}]\n{c['text']}"
        for c in context_chunks
    )
    return f"""你是一个企业知识库助手，基于以下参考资料回答用户问题。
如果参考资料不足以回答问题，请如实告知，不要编造。

=== 参考资料 ===
{context_text}
=== 用户问题 ===
{question}

=== 回答格式要求（严格遵守，参照示例） ===
1. 用 ## 标题分隔主题，标题前后各空一行
2. 有序列表项之间不要空行，紧挨排列
3. 无序列表项之间不要空行，紧挨排列
4. 重要术语、关键步骤用 **加粗**
5. 最后用 > 注明参考来源

正确示例：
## 软件安装

1. **双击安装包** install_msr.exe，进入安装界面。
2. 按照提示点击 **Next**，完成安装。
3. 安装完成后桌面会出现软件图标。

## 硬件连接

1. 通过 **USB 数据线** 将记录仪连接到电脑。
2. 等待约 20 秒，计算机自动识别硬件。
3. 双击桌面图标打开软件。

- 连接前请确认记录仪已**充满电**。
- 如果未自动识别，请检查 **USB 驱动** 是否安装。

> 来源：MSR/MSR165/用户手册.pdf"""
